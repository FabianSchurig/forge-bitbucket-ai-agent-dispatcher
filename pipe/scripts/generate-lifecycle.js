#!/usr/bin/env node
/**
 * generate-lifecycle.js
 *
 * Reads the `devcontainer.metadata` JSON label from a built devcontainer
 * image and emits a bash script that replays every `onCreateCommand`,
 * `updateContentCommand`, `postCreateCommand`, `postStartCommand`, and
 * `postAttachCommand` in the order they appear across all metadata
 * entries (a devcontainer image can have multiple, one per feature).
 *
 * We need this because `devcontainer build` does NOT execute lifecycle
 * commands – only `devcontainer up` does – but the Pipe runs the agent
 * via `docker build`/`docker run` for repeatability, so we have to replay
 * them manually.
 *
 * Usage:
 *   generate-lifecycle.js --metadata '<json>' --out <path>
 *
 * The script intentionally has zero npm dependencies so the runtime
 * image stays small.
 */
'use strict';

const fs = require('fs');

// ---------------------------------------------------------------------------
// Minimal CLI arg parser – avoids pulling in yargs/minimist.
// ---------------------------------------------------------------------------
function parseArgs(argv) {
    const out = {};
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === '--metadata') { out.metadata = argv[++i]; }
        else if (a === '--out') { out.out = argv[++i]; }
        else if (a === '--help' || a === '-h') { out.help = true; }
    }
    return out;
}

function usage() {
    console.error('Usage: generate-lifecycle.js --metadata <json> --out <path>');
}

const args = parseArgs(process.argv.slice(2));
if (args.help || !args.metadata || !args.out) {
    usage();
    process.exit(args.help ? 0 : 2);
}

// ---------------------------------------------------------------------------
// Parse the metadata.  The label is JSON-encoded; an empty image has '[]'.
// We tolerate malformed input by treating it as no metadata, since failing
// hard here would block the entire agent run for a non-essential feature.
// ---------------------------------------------------------------------------
let entries;
try {
    entries = JSON.parse(args.metadata || '[]');
} catch (err) {
    console.error(`WARN: could not parse devcontainer.metadata – ${err.message}`);
    entries = [];
}
if (!Array.isArray(entries)) { entries = [entries]; }

// ---------------------------------------------------------------------------
// Lifecycle command fields, in the order the devcontainer spec runs them.
// See https://containers.dev/implementors/json_reference/#lifecycle-scripts
// ---------------------------------------------------------------------------
const PHASES = [
    'onCreateCommand',
    'updateContentCommand',
    'postCreateCommand',
    'postStartCommand',
    'postAttachCommand',
];

/**
 * Normalise a lifecycle command into a flat list of shell strings.
 * The spec allows:
 *   - "echo hi"                 (string)
 *   - ["bash", "-c", "echo hi"] (string[])  -> single command (exec-form)
 *   - { "a": "echo a", "b": [...] } (object) -> parallel commands
 * For replay we run everything sequentially – parallelism in the spec is
 * an optimisation, not a semantic requirement.
 */
function normalise(cmd) {
    if (cmd == null) { return []; }
    if (typeof cmd === 'string') { return [cmd]; }
    if (Array.isArray(cmd)) {
        // exec-form: quote each arg and join.
        return [cmd.map(shellQuote).join(' ')];
    }
    if (typeof cmd === 'object') {
        return Object.values(cmd).flatMap(normalise);
    }
    return [];
}

function shellQuote(s) {
    // Single-quote and escape embedded single quotes – the canonical safe
    // shell quote.  Fine for arbitrary content because we never interpolate.
    return `'${String(s).replace(/'/g, `'\\''`)}'`;
}

// ---------------------------------------------------------------------------
// Build the bash script.
// ---------------------------------------------------------------------------
const lines = [
    '#!/usr/bin/env bash',
    '# AUTO-GENERATED by generate-lifecycle.js – do not edit by hand.',
    '# Replays devcontainer lifecycle commands extracted from the agent image.',
    'set -euo pipefail',
    '',
];

let total = 0;
for (const phase of PHASES) {
    const commands = entries.flatMap((entry) => normalise(entry && entry[phase]));
    if (commands.length === 0) { continue; }
    lines.push(`# --- ${phase} (${commands.length}) ---`);
    for (const c of commands) {
        // Wrap in `bash -c` so the command string can contain pipelines,
        // redirections, etc., exactly as authored in devcontainer.json.
        lines.push(`bash -c ${shellQuote(c)}`);
        total++;
    }
    lines.push('');
}

if (total === 0) {
    lines.push('# No lifecycle commands found.');
}

fs.writeFileSync(args.out, lines.join('\n') + '\n', { mode: 0o755 });
console.log(`generate-lifecycle.js: wrote ${total} command(s) to ${args.out}`);
